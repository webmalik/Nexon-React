const Footer = () => {
    const isDesktop = useMediaQuery({ minWidth: 992 });

    const handlePhoneClick = () => {
        window.open(`tel:${siteData.contact.phoneHref}`, '_blank');
    };

    const handleEmailClick = () => {
        window.open(`mailto:${siteData.contact.email}`, '_blank');
    };

    const handleInstagramClick = () => {
        window.open(siteData.links.instagram, '_blank');
    };

    const handleLinkedinClick = () => {
        window.open(siteData.links.linkedin, '_blank');
    };

    const handleWhatsappClick = () => {
        window.open(siteData.links.whatsapp, '_blank');
    };

    const renderLegalLinks = () => (
        <>
            {siteData.footer.legalLinks.map((link) => (
                <Link to={link.path} key={link.path}>
                    {link.label}
                </Link>
            ))}

            <button className="footer__cookie-button" type="button" onClick={openCookieSettings}>
                {siteData.footer.cookieSettings}
            </button>
        </>
    );

    const renderContacts = () => (
        <div className="footer__contacts">
            <button onClick={handlePhoneClick} className="contacts__phone" type="button">
                {siteData.contact.phone}
            </button>

            <button onClick={handleEmailClick} className="contacts__mail" type="button">
                {siteData.contact.email}
            </button>
        </div>
    );

    const renderPayments = () => (
        <div className="footer__inner footer__payments">
            <button className="visa" type="button">
                <img src={visa} alt="Visa" />
            </button>

            <button className="mastercard" type="button">
                <img src={mastercard} alt="Mastercard" />
            </button>
        </div>
    );

    const renderSocials = (showInstagram = true) => (
        <div className="footer__inner footer__socials">
            {showInstagram && (
                <button type="button" aria-label="Instagram" onClick={handleInstagramClick}>
                    <InstagramIcon />
                </button>
            )}

            <button type="button" aria-label="LinkedIn" onClick={handleLinkedinClick}>
                <LinkedinIcon />
            </button>

            <button type="button" aria-label="WhatsApp" onClick={handleWhatsappClick}>
                <WhatsappIcon />
            </button>
        </div>
    );

    return (
        <div className="footer not-sticky">
            <div className="container">
                {isDesktop ? (
                    <div className="footer__wrapper">
                        <div className="footer__item">
                            <h2 className="footer__logo">{siteData.name}</h2>

                            <div className="footer__inner">{renderSocials(false)}</div>

                            <div className="footer__inner footer__links">{renderLegalLinks()}</div>
                        </div>

                        <div className="footer__item">
                            <div className="footer__slug">{siteData.footer.slug}</div>
                            {renderPayments()}
                        </div>

                        <div className="footer__item">{renderContacts()}</div>
                    </div>
                ) : (
                    <div className="footer__wrapper">
                        <div className="footer__item">
                            <h2 className="footer__logo">{siteData.name}</h2>
                            <div className="footer__slug">{siteData.footer.slug}</div>
                        </div>

                        <div className="footer__item">
                            {renderContacts()}
                            {renderSocials(true)}
                        </div>

                        <div className="footer__item">
                            <div className="footer__inner footer__links">{renderLegalLinks()}</div>

                            {renderPayments()}
                        </div>
                    </div>
                )}
            </div>
        </div>
    );
};

export default Footer;
